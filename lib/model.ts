// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// Who gets ranked. The board covers every slug on the snapshot's watchlist (the floor, never the
// ceiling) and adds the early radar: pre-token protocols below the watchlist floor that pass the
// house's own visible rule for "not a wrapped, staked or bridged product of a token that already
// trades". A protocol is pre-token when its record carries no token at all: no market cap, no
// CoinGecko id, no symbol. Say "records no token", never "has no token": DefiLlama's record is not
// proof, and a protocol on the list may still carry a token its record does not show.
//
// The visible rule, from the snapshot's own fields only: the category is not Bridge, Canonical
// Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or CEX; the name carries no whole word
// wrapped, staked or staking; the name does not begin with an exchange's name (Binance, Coinbase,
// Bybit, Kraken, Bitget, OKX, Bitfinex, Gemini); the name does not end in a version marker. The
// house's rule has one more clause this file cannot see, DefiLlama's parentProtocol, so a protocol
// above the floor that the watchlist leaves out is never re-added: the house left it out, and the
// board does not second-guess a record it cannot read. That is why WBTC, Binance staked ETH,
// Coinbase Bridge and USDT0 never appear on this board, however large their TVL.
//
// Implied value follows only from the snapshot's own figures, the same function for every row:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -50, 150) per cent          (null change counts as 0)
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.65 + min(age_days, 1095) / 1095 x 0.35     (age unknown: 365 days)
//   chains     = 1 + 0.04 x min(max(chains - 1, 0), 5)
//   implied    = max(1, round(base x growthMult x maturity x chains))
//
// TVL is the size of the business a token would price. Seven-day growth is momentum: a protocol
// gaining TVL fast is worth more than a flat one of the same size, and a shrinking one less.
// Age is how long the protocol has run with no token: survival is the record of a launch that has
// not happened yet, so older protocols are discounted less. Chain breadth is distribution: a
// protocol live on more chains reaches more wallets on launch day. No protocol name is ever
// special-cased, and no row is hand-picked: the same function scores every row, and the dashboard
// prints the formula with the constants it runs.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

